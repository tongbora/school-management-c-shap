
using System.Drawing;
using System.Drawing.Imaging;

namespace SchoolManagement.Desktop.Controls.Students;

public static class StudentPhotoStorage
{
    private const long MaxSize = 5 * 1024 * 1024;

    public static string StorageDirectory =>
        Path.Combine(
            Environment.GetFolderPath(
                Environment.SpecialFolder.LocalApplicationData),
            "SchoolManagement",
            "StudentPhotos");

    public static string SavePhoto(string sourcePath)
    {
        var fileInfo = new FileInfo(sourcePath);

        if (!fileInfo.Exists)
            throw new FileNotFoundException("Photo not found.");

        if (fileInfo.Length == 0 ||
            fileInfo.Length > MaxSize)
        {
            throw new InvalidOperationException(
                "Photo must be smaller than 5 MB.");
        }

        using var image = Image.FromFile(sourcePath);

        string extension;

        if (image.RawFormat.Guid == ImageFormat.Jpeg.Guid)
            extension = ".jpg";
        else if (image.RawFormat.Guid == ImageFormat.Png.Guid)
            extension = ".png";
        else
            throw new InvalidOperationException(
                "Only JPG and PNG photos are supported.");

        Directory.CreateDirectory(StorageDirectory);

        string filename =
            $"{Guid.NewGuid():N}{extension}";

        string destination =
            Path.Combine(StorageDirectory, filename);

        File.Copy(sourcePath, destination);

        return filename;
    }

    public static Image? LoadPhoto(string? filename)
    {
        if (string.IsNullOrWhiteSpace(filename))
            return null;

        // Accept only filenames generated by this application.
        string name = Path.GetFileName(filename);
        string id = Path.GetFileNameWithoutExtension(name);
        string extension = Path.GetExtension(name).ToLowerInvariant();

        if (name != filename ||
            id.Length != 32 ||
            !Guid.TryParseExact(id, "N", out _) ||
            (extension != ".jpg" && extension != ".png"))
        {
            return null;
        }

        string path = Path.Combine(StorageDirectory, name);

        if (!File.Exists(path))
            return null;

        using var original = Image.FromFile(path);

        // Clone the image to avoid locking the file.
        return new Bitmap(original);
    }

    public static void DeletePhoto(string filename)
    {
        if (string.IsNullOrWhiteSpace(filename))
            return;

        string name = Path.GetFileName(filename);
        string id = Path.GetFileNameWithoutExtension(name);
        string extension = Path.GetExtension(name).ToLowerInvariant();

        if (name != filename ||
            !Guid.TryParseExact(id, "N", out _) ||
            (extension != ".jpg" && extension != ".png"))
            return;

        string path = Path.Combine(StorageDirectory, name);

        if (File.Exists(path))
            File.Delete(path);
    }
}
